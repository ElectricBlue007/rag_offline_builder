"""Automated chunk review agent for embedding readiness.

Consumes `index.json` output (`flat_chunk_view`) and reviews each chunk as an
operator would before embedding. The agent does not mutate chunks; it emits
rule-level issues, scores, and a final decision.
"""

from __future__ import annotations

import math
import re
import unicodedata
from collections import Counter
from dataclasses import asdict, dataclass, field
from typing import Any, Iterable


@dataclass
class ChunkReviewIssue:
    rule_id: int
    rule_name: str
    severity: str
    action: str
    message: str

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


@dataclass
class ChunkReviewResult:
    chunk_id: str
    structural_score: int
    token_score: int
    semantic_score: int
    retrieval_score: int
    context_score: int
    embedding_score: int
    self_sufficiency_score: int
    embedding_stability_score: int
    final_score: int
    decision: str
    issues: list[ChunkReviewIssue] = field(default_factory=list)
    recommended_action: str | None = None
    metadata: dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> dict[str, Any]:
        data = asdict(self)
        data["issues"] = [issue.to_dict() for issue in self.issues]
        return data


@dataclass
class IndexReviewReport:
    chunk_reviews: list[ChunkReviewResult]
    summary: dict[str, Any]

    def to_dict(self) -> dict[str, Any]:
        return {
            "chunk_reviews": [review.to_dict() for review in self.chunk_reviews],
            "summary": self.summary,
        }


class ChunkReviewAgent:
    """Review chunk candidates for embedding readiness."""

    E5_MIN_TOKENS = 50
    DANGEROUSLY_SMALL_TOKENS = 20
    TOO_LARGE_TOKENS = 800
    VERY_LARGE_TOKENS = 1200

    _SYMBOLS_ONLY = re.compile(r"^[\W_]+$", re.UNICODE)
    _HEADING_ONLY = re.compile(r"^\s*#{1,6}\s+\S.*$", re.MULTILINE)
    _FENCE = re.compile(r"^\s*(```|~~~)", re.MULTILINE)
    _NAVIGATION = re.compile(r"\b(previous|next|home|back|edit this page|table of contents)\b", re.IGNORECASE)
    _BADGE = re.compile(r"!\[.*?\]\(.*?(badge|shields|pypi|discord|downloads).*?\)", re.IGNORECASE)
    _FOOTER = re.compile(r"\b(copyright|all rights reserved|powered by|generated by)\b", re.IGNORECASE)
    _LICENSE = re.compile(r"\b(MIT License|Apache License|BSD License|GPL|licensed under)\b", re.IGNORECASE)
    _DECORATIVE_OCR = re.compile(
        r"\b(google logo|abstract geometric shape|faceted geometric|crystal|gemstone|bottom left corner|bottom right corner|decorative)\b",
        re.IGNORECASE,
    )
    _DEFINITION = re.compile(r"\b[A-Z][A-Za-z0-9_]*(?:Chunker|Embeddings|Pipeline|API)?\s+(?:is|are|means|refers to)\b")
    _PROCEDURE = re.compile(r"\b(step\s*\d+|first|then|next|finally|install|run|execute|configure)\b", re.IGNORECASE)
    _INSTRUCTION = re.compile(r"\b(must|should|click|select|enter|use|set|create|add|remove)\b", re.IGNORECASE)
    _KNOWLEDGE = re.compile(r"\b(because|therefore|however|means|allows|enables|used to|depends on)\b", re.IGNORECASE)
    _ACTIONABLE = re.compile(r"\b(install|run|configure|set|create|use|call|send|parse|return|execute)\b", re.IGNORECASE)
    _ENTITY = re.compile(r"\b[A-Z][A-Za-z0-9_]*(?:Chunker|Embeddings|Pipeline|API|Config|Model)?\b")
    _RELATIONSHIP = re.compile(r"\b(uses|calls|depends on|requires|creates|returns|maps to|connects to)\b", re.IGNORECASE)
    _CROSS_REFERENCE = re.compile(r"\b(?:see|refer to|as described in|more in)\s+([A-Z][A-Za-z0-9 &/_-]+)", re.IGNORECASE)
    _SEARCHABLE = re.compile(r"\b(chunk|embedding|retrieval|semantic|model|api|config|install|markdown|document)\b", re.IGNORECASE)
    _MOJIBAKE = re.compile(r"(â|Ã|آ)")

    def review_index(self, index: dict[str, Any], embedding_model: str = "e5") -> IndexReviewReport:
        chunks = index.get("flat_chunk_view", [])
        reviews = self.review_chunks(chunks, embedding_model=embedding_model)
        summary = self._summary(reviews)
        return IndexReviewReport(chunk_reviews=reviews, summary=summary)

    def review_chunks(self, chunks: list[dict[str, Any]], embedding_model: str = "e5") -> list[ChunkReviewResult]:
        normalized_texts = [self._fingerprint(chunk.get("text", "")) for chunk in chunks]
        exact_counts = Counter(normalized_texts)
        reviews = []

        for index, chunk in enumerate(chunks):
            issues = []
            text = chunk.get("text", "") or ""
            token_count = self._token_count(chunk)
            metadata = self._metadata(chunk, token_count, embedding_model)

            self._apply_structural_rules(chunk, text, issues)
            self._apply_token_rules(text, token_count, issues)
            self._apply_semantic_rules(chunk, text, issues, metadata)
            self._apply_retrieval_rules(text, issues, metadata)
            self._apply_noise_rules(text, chunk, issues, exact_counts, normalized_texts, index)
            self._apply_context_rules(chunk, issues)
            self._apply_embedding_rules(text, chunk, embedding_model, issues, metadata)

            scores = self._scores(chunk, text, token_count, issues, metadata)
            final_score = self._final_score(scores, issues)
            decision = self._decision(final_score, issues)
            recommended_action = self._recommended_action(decision, issues)

            reviews.append(
                ChunkReviewResult(
                    chunk_id=chunk.get("chunk_id", f"chunk_{index + 1}"),
                    structural_score=scores["structural_score"],
                    token_score=scores["token_score"],
                    semantic_score=scores["semantic_score"],
                    retrieval_score=scores["retrieval_score"],
                    context_score=scores["context_score"],
                    embedding_score=scores["embedding_score"],
                    self_sufficiency_score=scores["self_sufficiency_score"],
                    embedding_stability_score=scores["embedding_stability_score"],
                    final_score=final_score,
                    decision=decision,
                    issues=issues,
                    recommended_action=recommended_action,
                    metadata=metadata,
                )
            )

        return reviews

    def _apply_structural_rules(self, chunk: dict[str, Any], text: str, issues: list[ChunkReviewIssue]) -> None:
        stripped = text.strip()
        if not stripped:
            issues.append(self._issue(301, "Chunk Empty", "critical", "REJECT", "Chunk text is empty."))
            return
        if self._SYMBOLS_ONLY.match(stripped):
            issues.append(self._issue(302, "Only Symbols", "critical", "REJECT", "Chunk contains only symbols."))
        if self._is_only_heading(stripped):
            issues.append(self._issue(303, "Only Heading", "high", "MERGE", "Chunk contains only a heading."))
        if self._broken_markdown(text):
            issues.append(self._issue(304, "Broken Markdown", "high", "REPAIR", "Markdown syntax appears broken."))
        if len(self._FENCE.findall(text)) % 2:
            issues.append(self._issue(305, "Broken Code Block", "critical", "RECHUNK", "Code fence is not balanced."))
        if self._broken_table(text):
            issues.append(self._issue(306, "Broken Table", "high", "REPAIR", "Markdown table columns are inconsistent."))
        if self._broken_list(text):
            issues.append(self._issue(307, "Broken List", "medium", "REPAIR", "List indentation or markers are inconsistent."))
        if not chunk.get("heading_path"):
            issues.append(self._issue(308, "Heading Path Exists", "high", "REPAIR", "Chunk has no heading path."))
        if not chunk.get("parent_section_id"):
            issues.append(self._issue(309, "Parent Context Exists", "medium", "REPAIR", "Chunk has no parent section id."))
        if not chunk.get("debug_metadata") or not chunk.get("evaluation_metadata"):
            issues.append(self._issue(310, "Chunk Metadata Exists", "medium", "REPAIR", "Chunk metadata is incomplete."))

    def _apply_token_rules(self, text: str, token_count: int, issues: list[ChunkReviewIssue]) -> None:
        if token_count < self.DANGEROUSLY_SMALL_TOKENS:
            issues.append(self._issue(312, "Dangerously Small", "critical", "RECHUNK", "Chunk is dangerously small."))
        elif token_count < self.E5_MIN_TOKENS:
            issues.append(self._issue(311, "Too Small Chunk", "high", "REPAIR", "Chunk is below E5 minimum semantic mass."))
        if token_count > self.VERY_LARGE_TOKENS:
            issues.append(self._issue(314, "Very Large", "critical", "RECHUNK", "Chunk is far above embedding-safe size."))
        elif token_count > self.TOO_LARGE_TOKENS:
            issues.append(self._issue(313, "Too Large", "high", "RECHUNK", "Chunk is too large."))
        if self._token_density(text) < 0.2:
            issues.append(self._issue(315, "Token Density", "medium", "REPAIR", "Token density is too low."))

    def _apply_semantic_rules(
        self,
        chunk: dict[str, Any],
        text: str,
        issues: list[ChunkReviewIssue],
        metadata: dict[str, Any],
    ) -> None:
        if metadata["semantic_density"] < 0.25:
            issues.append(self._issue(316, "Semantic Density", "high", "REPAIR", "Chunk has low semantic density."))
        metadata["definition_score"] = 100 if self._DEFINITION.search(text) else 35
        metadata["procedure_score"] = 100 if self._PROCEDURE.search(text) else 35
        metadata["instruction_score"] = 100 if self._INSTRUCTION.search(text) else 35
        metadata["knowledge_score"] = 100 if self._KNOWLEDGE.search(text) else 45
        if metadata["definition_score"] < 50:
            issues.append(self._issue(317, "Definition Score", "info", "NONE", "Chunk is not definition-oriented."))
        if metadata["procedure_score"] < 50:
            issues.append(self._issue(318, "Procedure Score", "info", "NONE", "Chunk is not procedure-oriented."))
        if metadata["instruction_score"] < 50:
            issues.append(self._issue(319, "Instruction Score", "info", "NONE", "Chunk has few explicit instructions."))
        if metadata["knowledge_score"] < 50:
            issues.append(self._issue(320, "Knowledge Score", "info", "NONE", "Chunk has limited explanatory knowledge markers."))
        if not self._answerable(text):
            issues.append(self._issue(321, "Question Answerability", "critical", "REJECT", "Chunk is unlikely to answer a user query."))
        if self._self_sufficiency(chunk, text) <= 50:
            issues.append(self._issue(322, "Standalone Understandability", "high", "REPAIR", "Chunk is not understandable alone."))
        if self._context_dependency(text) > 65:
            issues.append(self._issue(323, "Context Dependency", "medium", "REPAIR", "Chunk depends strongly on neighboring context."))
        if self._topic_count(text) > 3:
            issues.append(self._issue(324, "Topic Consistency", "medium", "RECHUNK", "Chunk appears to mix multiple topics."))
        if self._cohesion(chunk, text) < 45:
            issues.append(self._issue(325, "Semantic Cohesion", "medium", "RECHUNK", "Chunk semantic cohesion is weak."))

    def _apply_retrieval_rules(self, text: str, issues: list[ChunkReviewIssue], metadata: dict[str, Any]) -> None:
        metadata["entities"] = self._entities(text)
        metadata["keywords"] = self._keywords(text)
        if not self._retrievable(text):
            issues.append(self._issue(326, "Contains Retrievable Information", "critical", "REJECT", "No retrievable information found."))
        if not self._ACTIONABLE.search(text):
            issues.append(self._issue(327, "Contains Actionable Information", "info", "NONE", "No actionable instruction found."))
        if not self._DEFINITION.search(text):
            issues.append(self._issue(328, "Contains Definition", "info", "NONE", "No explicit definition found."))
        if not metadata["entities"]:
            issues.append(self._issue(329, "Contains Entities", "medium", "REPAIR", "No clear named entities found."))
        if not metadata["keywords"]:
            issues.append(self._issue(330, "Contains Keywords", "medium", "REPAIR", "No strong searchable keywords found."))
        if not self._SEARCHABLE.search(text):
            issues.append(self._issue(331, "Contains Searchable Concepts", "medium", "REPAIR", "No searchable concepts found."))
        if not self._RELATIONSHIP.search(text):
            issues.append(self._issue(332, "Contains Relationships", "info", "NONE", "No explicit relationship statement found."))

    def _apply_noise_rules(
        self,
        text: str,
        chunk: dict[str, Any],
        issues: list[ChunkReviewIssue],
        exact_counts: Counter,
        normalized_texts: list[str],
        index: int,
    ) -> None:
        if self._NAVIGATION.search(text):
            issues.append(self._issue(333, "Navigation Detection", "critical", "REJECT", "Navigation text detected."))
        if self._BADGE.search(text):
            issues.append(self._issue(334, "Badge Detection", "critical", "REJECT", "Badge noise detected."))
        if self._FOOTER.search(text):
            issues.append(self._issue(335, "Footer Detection", "high", "REJECT", "Footer text detected."))
        if self._decorative_ocr_noise(text):
            issues.append(self._issue(336, "Boilerplate Detection", "critical", "REJECT", "Decorative OCR image-caption noise detected."))
        elif self._boilerplate(text):
            issues.append(self._issue(336, "Boilerplate Detection", "medium", "REPAIR", "Boilerplate-like text detected."))
        if self._LICENSE.search(text):
            issues.append(self._issue(337, "License Detection", "medium", "REPAIR", "License text detected."))
        fingerprint = self._fingerprint(text)
        if fingerprint and exact_counts[fingerprint] > 1:
            issues.append(self._issue(338, "Repeated Chunk Detection", "medium", "REJECT", "Exact repeated chunk detected."))
        if self._has_near_duplicate(fingerprint, normalized_texts, index):
            issues.append(self._issue(339, "Near Duplicate Chunk Detection", "medium", "REPAIR", "Near duplicate chunk detected."))

    def _apply_context_rules(self, chunk: dict[str, Any], issues: list[ChunkReviewIssue]) -> None:
        heading_path = chunk.get("heading_path") or []
        debug_metadata = chunk.get("debug_metadata") or {}
        if not heading_path:
            issues.append(self._issue(340, "Heading Injection Exists", "high", "REPAIR", "Heading injection is missing."))
        if not chunk.get("parent_section_id"):
            issues.append(self._issue(341, "Section Context Exists", "medium", "REPAIR", "Section context is missing."))
        if not heading_path[:1]:
            issues.append(self._issue(342, "Document Context Exists", "medium", "REPAIR", "Document-level context is missing."))
        if self._CROSS_REFERENCE.search(chunk.get("text", "")) and "cross_references" not in debug_metadata:
            issues.append(self._issue(343, "Cross Reference Metadata Exists", "medium", "REPAIR", "Cross reference metadata is missing."))

    def _apply_embedding_rules(
        self,
        text: str,
        chunk: dict[str, Any],
        embedding_model: str,
        issues: list[ChunkReviewIssue],
        metadata: dict[str, Any],
    ) -> None:
        if embedding_model.lower().startswith("e5") and not text.lstrip().lower().startswith("passage:"):
            issues.append(self._issue(344, "Prefix Validation", "medium", "REPAIR", "E5 passage prefix is missing."))
        metadata["language"] = self._language(text)
        if metadata["language"] == "unknown":
            issues.append(self._issue(345, "Language Validation", "medium", "REPAIR", "Language could not be identified."))
        if not unicodedata.is_normalized("NFC", text):
            issues.append(self._issue(346, "Unicode Validation", "medium", "REPAIR", "Text is not NFC normalized."))
        if self._MOJIBAKE.search(text):
            issues.append(self._issue(347, "Encoding Validation", "high", "REPAIR", "Encoding/mojibake artifacts detected."))
        if self._mixed_language(text):
            issues.append(self._issue(348, "Mixed Language Detection", "low", "REPAIR", "Mixed language content detected."))
        metadata["embedding_cost_score"] = self._embedding_cost_score(metadata["token_count"])
        if metadata["embedding_cost_score"] < 50:
            issues.append(self._issue(349, "Embedding Cost Score", "medium", "RECHUNK", "Embedding cost is high for this chunk."))
        metadata["embedding_readiness_score"] = self._embedding_readiness_score(chunk, issues, metadata)
        if metadata["embedding_readiness_score"] < 75:
            issues.append(self._issue(350, "Embedding Readiness Score", "high", "REPAIR", "Embedding readiness is below target."))

    def _scores(
        self,
        chunk: dict[str, Any],
        text: str,
        token_count: int,
        issues: list[ChunkReviewIssue],
        metadata: dict[str, Any],
    ) -> dict[str, int]:
        structural_score = self._category_score(issues, range(301, 311))
        token_score = self._category_score(issues, range(311, 316))
        semantic_score = self._category_score(issues, range(316, 326), ignore_info=True)
        retrieval_score = self._category_score(issues, range(326, 333), ignore_info=True)
        context_score = self._category_score(issues, range(340, 344))
        embedding_score = self._category_score(issues, range(344, 351))
        self_sufficiency_score = self._self_sufficiency(chunk, text)
        stability_score = self._embedding_stability_score(token_count, metadata, issues)
        return {
            "structural_score": structural_score,
            "token_score": token_score,
            "semantic_score": semantic_score,
            "retrieval_score": retrieval_score,
            "context_score": context_score,
            "embedding_score": embedding_score,
            "self_sufficiency_score": self_sufficiency_score,
            "embedding_stability_score": stability_score,
        }

    def _final_score(self, scores: dict[str, int], issues: list[ChunkReviewIssue]) -> int:
        weighted = (
            scores["structural_score"] * 0.16
            + scores["token_score"] * 0.12
            + scores["semantic_score"] * 0.18
            + scores["retrieval_score"] * 0.18
            + scores["context_score"] * 0.12
            + scores["embedding_score"] * 0.12
            + scores["self_sufficiency_score"] * 0.06
            + scores["embedding_stability_score"] * 0.06
        )
        if any(issue.severity == "critical" for issue in issues):
            weighted = min(weighted, 49)
        return int(round(max(0, min(100, weighted))))

    @staticmethod
    def _decision(final_score: int, issues: list[ChunkReviewIssue]) -> str:
        if any(issue.action == "REJECT" and issue.severity == "critical" for issue in issues):
            return "REJECT"
        if any(issue.action == "RECHUNK" and issue.severity == "critical" for issue in issues):
            return "RECHUNK"
        if final_score >= 90:
            return "APPROVE"
        if final_score >= 75:
            return "REPAIR"
        if final_score >= 50:
            return "RECHUNK"
        return "REJECT"

    @staticmethod
    def _recommended_action(decision: str, issues: list[ChunkReviewIssue]) -> str | None:
        actionable = [issue for issue in issues if issue.action != "NONE"]
        if decision == "APPROVE" or not actionable:
            return None
        first = actionable[0]
        return f"{first.action}: {first.message}"

    def _metadata(self, chunk: dict[str, Any], token_count: int, embedding_model: str) -> dict[str, Any]:
        text = chunk.get("text", "") or ""
        return {
            "token_count": token_count,
            "token_density": self._token_density(text),
            "semantic_density": self._semantic_density(text),
            "embedding_model": embedding_model,
        }

    @staticmethod
    def _issue(rule_id: int, rule_name: str, severity: str, action: str, message: str) -> ChunkReviewIssue:
        return ChunkReviewIssue(rule_id=rule_id, rule_name=rule_name, severity=severity, action=action, message=message)

    @staticmethod
    def _token_count(chunk: dict[str, Any]) -> int:
        estimate = chunk.get("token_estimate")
        if isinstance(estimate, int) and estimate > 0:
            return estimate
        text = chunk.get("text", "") or ""
        return max(len(re.findall(r"\S+", text)), math.ceil(len(text) / 4))

    @staticmethod
    def _token_density(text: str) -> float:
        if not text:
            return 0.0
        return round(len(re.findall(r"[A-Za-z0-9_]+", text)) / max(len(text), 1), 3)

    @staticmethod
    def _semantic_density(text: str) -> float:
        tokens = re.findall(r"[A-Za-z0-9_]+", text.lower())
        if not tokens:
            return 0.0
        unique_ratio = len(set(tokens)) / len(tokens)
        long_word_ratio = len([token for token in tokens if len(token) >= 5]) / len(tokens)
        return round(min(1.0, unique_ratio * 0.65 + long_word_ratio * 0.35), 3)

    @classmethod
    def _is_only_heading(cls, stripped: str) -> bool:
        return bool(cls._HEADING_ONLY.match(stripped)) and len(stripped.splitlines()) == 1

    @staticmethod
    def _broken_markdown(text: str) -> bool:
        return text.count("[") != text.count("]") or text.count("(") != text.count(")")

    @staticmethod
    def _broken_table(text: str) -> bool:
        rows = [line for line in text.splitlines() if "|" in line and not re.match(r"^\s*\|?\s*:?-{3,}", line)]
        if len(rows) < 2:
            return False
        counts = [row.count("|") for row in rows]
        return len(set(counts)) > 1

    @staticmethod
    def _broken_list(text: str) -> bool:
        list_lines = [line for line in text.splitlines() if re.match(r"^\s*([-*+]|\d+[.)])", line)]
        if not list_lines:
            return False
        return any(not re.match(r"^\s*([-*+]|\d+[.)])\s+\S", line) for line in list_lines)

    @staticmethod
    def _answerable(text: str) -> bool:
        return bool(re.search(r"\b(is|are|how|why|when|where|install|configure|use|step|example|api|returns?)\b", text, re.IGNORECASE))

    @staticmethod
    def _context_dependency(text: str) -> int:
        dependency_markers = len(re.findall(r"\b(this|that|it|they|above|below|previous|following|same)\b", text, re.IGNORECASE))
        token_count = max(1, len(re.findall(r"\S+", text)))
        return int(min(100, dependency_markers / token_count * 250))

    @staticmethod
    def _topic_count(text: str) -> int:
        terms = set(re.findall(r"[A-Za-z]{5,}", text.lower()))
        groups = 0
        for keywords in (
            {"install", "package", "python", "pip", "configure"},
            {"api", "endpoint", "request", "response", "users"},
            {"embedding", "retrieval", "chunk", "semantic", "vector"},
            {"license", "copyright", "permission"},
            {"pizza", "cheese", "flour", "recipe"},
        ):
            if terms & keywords:
                groups += 1
        return groups

    @staticmethod
    def _cohesion(chunk: dict[str, Any], text: str) -> int:
        existing = (chunk.get("evaluation_metadata") or {}).get("chunk_coherence_score")
        if isinstance(existing, (int, float)):
            return int(existing * 100)
        sentences = [s for s in re.split(r"[.!?]\s+", text) if s.strip()]
        if len(sentences) <= 1:
            return 65
        first_terms = set(re.findall(r"[A-Za-z0-9_]+", sentences[0].lower()))
        overlap_scores = []
        for sentence in sentences[1:]:
            terms = set(re.findall(r"[A-Za-z0-9_]+", sentence.lower()))
            if terms:
                overlap_scores.append(len(first_terms & terms) / len(first_terms | terms))
        return int((sum(overlap_scores) / max(1, len(overlap_scores))) * 100)

    @classmethod
    def _retrievable(cls, text: str) -> bool:
        return bool(cls._SEARCHABLE.search(text) or cls._DEFINITION.search(text) or cls._PROCEDURE.search(text))

    @classmethod
    def _entities(cls, text: str) -> list[str]:
        return sorted(set(match.group(0) for match in cls._ENTITY.finditer(text)))

    @classmethod
    def _keywords(cls, text: str) -> list[str]:
        words = [word.lower() for word in re.findall(r"[A-Za-z]{4,}", text)]
        domain = {
            "chunk", "chunks", "chunking", "embedding", "embeddings", "retrieval", "semantic",
            "model", "api", "config", "install", "markdown", "document", "pipeline",
            "chonkie", "semanticchunker", "autoembeddings",
        }
        words = [word for word in words if word in domain]
        stop = {"this", "that", "with", "from", "your", "have", "will", "into", "text"}
        counts = Counter(word for word in words if word not in stop)
        return [word for word, count in counts.most_common(10) if count >= 1]

    @classmethod
    def _boilerplate(cls, text: str) -> bool:
        return bool(re.search(r"\b(author|contributors?|maintainers?|generated|logo|abstract geometric shape)\b", text, re.IGNORECASE))

    @classmethod
    def _decorative_ocr_noise(cls, text: str) -> bool:
        if not cls._DECORATIVE_OCR.search(text):
            return False
        domain_terms = re.findall(
            r"\b(prompt|model|token|temperature|top-k|top-p|json|classification|few-shot|zero-shot|embedding|retrieval)\b",
            text,
            re.IGNORECASE,
        )
        return len(domain_terms) < 2

    @staticmethod
    def _fingerprint(text: str) -> str:
        return re.sub(r"\s+", " ", text.strip().lower())

    def _has_near_duplicate(self, fingerprint: str, normalized_texts: list[str], index: int) -> bool:
        if not fingerprint:
            return False
        terms = set(fingerprint.split())
        if not terms:
            return False
        for other_index, other in enumerate(normalized_texts):
            if other_index == index or not other:
                continue
            other_terms = set(other.split())
            if not other_terms:
                continue
            similarity = len(terms & other_terms) / len(terms | other_terms)
            if similarity >= 0.75:
                return True
        return False

    @staticmethod
    def _language(text: str) -> str:
        latin = len(re.findall(r"[A-Za-z]", text))
        arabic = len(re.findall(r"[\u0600-\u06FF]", text))
        cjk = len(re.findall(r"[\u4E00-\u9FFF]", text))
        total = latin + arabic + cjk
        if total == 0:
            return "unknown"
        if arabic / total > 0.5:
            return "arabic_or_persian"
        if cjk / total > 0.5:
            return "cjk"
        return "latin"

    @staticmethod
    def _mixed_language(text: str) -> bool:
        scripts = [
            bool(re.search(r"[A-Za-z]", text)),
            bool(re.search(r"[\u0600-\u06FF]", text)),
            bool(re.search(r"[\u4E00-\u9FFF]", text)),
        ]
        return sum(scripts) >= 2

    @staticmethod
    def _embedding_cost_score(token_count: int) -> int:
        if token_count <= 500:
            return 100
        if token_count <= 800:
            return 75
        if token_count <= 1200:
            return 45
        return 10

    def _embedding_readiness_score(
        self,
        chunk: dict[str, Any],
        issues: list[ChunkReviewIssue],
        metadata: dict[str, Any],
    ) -> int:
        score = 100
        for issue in issues:
            if issue.rule_id == 344:
                score -= 8
            elif 301 <= issue.rule_id <= 350 and issue.severity == "critical":
                score -= 35
            elif issue.severity == "high":
                score -= 18
            elif issue.severity == "medium":
                score -= 8
        score = min(score, metadata["embedding_cost_score"])
        return max(0, min(100, score))

    @staticmethod
    def _category_score(issues: Iterable[ChunkReviewIssue], rule_range: range, ignore_info: bool = False) -> int:
        score = 100
        for issue in issues:
            if issue.rule_id not in rule_range:
                continue
            if ignore_info and issue.severity == "info":
                continue
            if issue.severity == "critical":
                score -= 55
            elif issue.severity == "high":
                score -= 30
            elif issue.severity == "medium":
                score -= 15
            elif issue.severity == "low":
                score -= 5
        return max(0, min(100, score))

    def _self_sufficiency(self, chunk: dict[str, Any], text: str) -> int:
        score = 30
        word_count = len(re.findall(r"\S+", text))
        if chunk.get("heading_path"):
            score += 25
        if self._answerable(text):
            score += 20
        if self._entities(text):
            score += 10
        if word_count >= self.E5_MIN_TOKENS:
            score += 15
        if word_count < 20:
            score -= 25
        score -= min(25, self._context_dependency(text) // 2)
        return max(0, min(100, score))

    def _embedding_stability_score(
        self,
        token_count: int,
        metadata: dict[str, Any],
        issues: list[ChunkReviewIssue],
    ) -> int:
        score = 100
        if token_count < self.E5_MIN_TOKENS:
            score -= 25
        if token_count > self.TOO_LARGE_TOKENS:
            score -= 25
        if metadata["semantic_density"] < 0.25:
            score -= 20
        if any(issue.rule_id in {346, 347, 348} for issue in issues):
            score -= 20
        return max(0, min(100, score))

    @staticmethod
    def _summary(reviews: list[ChunkReviewResult]) -> dict[str, Any]:
        decisions = Counter(review.decision for review in reviews)
        avg_score = round(sum(review.final_score for review in reviews) / max(1, len(reviews)), 2)
        return {
            "chunk_count": len(reviews),
            "average_final_score": avg_score,
            "decisions": dict(decisions),
            "ready_for_embedding": (
                decisions.get("REJECT", 0) == 0
                and decisions.get("RECHUNK", 0) == 0
                and decisions.get("REPAIR", 0) == 0
            ),
        }
